-- JS Number(): numbers, numeric strings, "" → 0; anything else → null
create or replace function private.jnum(v jsonb) returns numeric
language plpgsql immutable set search_path = '' as $$
declare t text;
begin
  if v is null then return null; end if;
  if jsonb_typeof(v) = 'number' then return (v #>> '{}')::numeric; end if;
  if jsonb_typeof(v) = 'string' then
    t := btrim(v #>> '{}');
    if t = '' then return 0; end if;
    if t ~ '^[+-]?(\d+\.?\d*|\.\d+)$' and length(t) <= 20 then return t::numeric; end if;
  end if;
  return null;
end $$;

-- JS parseInt(): leading integer of a number/string, else null
create or replace function private.jint(v jsonb) returns int
language plpgsql immutable set search_path = '' as $$
declare t text; m text;
begin
  if v is null then return null; end if;
  if jsonb_typeof(v) = 'number' then
    if abs((v #>> '{}')::numeric) >= 1e9 then return null; end if;
    return trunc((v #>> '{}')::numeric)::int;
  end if;
  if jsonb_typeof(v) = 'string' then
    t := btrim(v #>> '{}');
    m := substring(t from '^[+-]?\d{1,9}');
    return m::int;
  end if;
  return null;
end $$;

-- JS truthiness (for !!x)
create or replace function private.truthy(v jsonb) returns boolean
language sql immutable set search_path = '' as $$
  select case jsonb_typeof(v)
    when 'boolean' then v = 'true'::jsonb
    when 'number'  then (v #>> '{}')::numeric <> 0
    when 'string'  then (v #>> '{}') <> ''
    when 'object'  then true
    when 'array'   then true
    else false end $$;

-- engine.js money(): "1,000 ج" / "12.50 ج"
create or replace function private.money(x numeric) returns text
language sql immutable set search_path = '' as $$
  select case when round(x, 2) = trunc(round(x, 2))
    then to_char(round(x, 2), 'FM999,999,999,990')
    else to_char(round(x, 2), 'FM999,999,999,990.00') end || ' ج' $$;

-- prints a number like JS does (10, 12.5 — no trailing zeros)
create or replace function private.num_txt(x numeric) returns text
language sql immutable set search_path = '' as $$ select trim_scale(x)::text $$;

-- engine.js phoneNorm()
create or replace function private.phone_norm(p text) returns text
language plpgsql immutable set search_path = '' as $$
declare d text;
begin
  d := regexp_replace(translate(coalesce(p, ''), '٠١٢٣٤٥٦٧٨٩', '0123456789'), '\D', '', 'g');
  if left(d, 4) = '0020' then d := substr(d, 5); end if;
  if left(d, 2) = '20' and length(d) = 12 then d := substr(d, 3); end if;
  if length(d) = 10 and left(d, 1) = '1' then d := '0' || d; end if;
  if d ~ '^01[0125]\d{8}$' then return d; end if;
  return null;
end $$;

-- engine.js distKm() (Haversine, km)
create or replace function private.dist_km(lat1 float8, lng1 float8, lat2 float8, lng2 float8) returns float8
language sql immutable set search_path = '' as $$
  select 2 * 6371 * asin(least(1, sqrt(
    sin(radians(lat2 - lat1) / 2) ^ 2 + cos(radians(lat1)) * cos(radians(lat2)) * sin(radians(lng2 - lng1) / 2) ^ 2))) $$;

-- engine.js validLL()
create or replace function private.valid_ll(lat jsonb, lng jsonb) returns boolean
language plpgsql immutable set search_path = '' as $$
declare a numeric; b numeric;
begin
  if lat is null or lng is null or jsonb_typeof(lat) not in ('number','string') or jsonb_typeof(lng) not in ('number','string') then return false; end if;
  if lat #>> '{}' = '' or lng #>> '{}' = '' then return false; end if;
  a := private.jnum(lat); b := private.jnum(lng);
  return a is not null and b is not null and abs(a) <= 90 and abs(b) <= 180;
end $$;

-- engine.js lineUnit(): unit price for one product with selections { groupId: [choiceIndex, …] }
create or replace function private.line_unit(p_options jsonb, p_price numeric, p_sel jsonb) returns jsonb
language plpgsql immutable set search_path = '' as $$
declare
  base numeric := coalesce(p_price, 0); factor numeric := 1; picked jsonb := '[]'::jsonb;
  g jsonb; s jsonb; idx int[]; i int; c jsonb; v jsonb; n numeric; nch int; f numeric;
begin
  for g in select value from jsonb_array_elements(case when jsonb_typeof(p_options) = 'array' then p_options else '[]'::jsonb end) loop
    s := case when jsonb_typeof(p_sel) = 'object' then p_sel -> (g ->> 'id') end;
    nch := case when jsonb_typeof(g -> 'choices') = 'array' then jsonb_array_length(g -> 'choices') else 0 end;
    idx := '{}';
    if jsonb_typeof(s) = 'array' then
      for v in select value from jsonb_array_elements(s) loop
        n := private.jnum(v);
        if n is not null and n = trunc(n) and n >= 0 and n < nch and not (n::int = any(idx)) then idx := idx || n::int; end if;
      end loop;
    end if;
    if g ->> 'type' = 'single' and cardinality(idx) > 1 then
      raise exception '%', format('اختار حاجة واحدة بس في "%s"', g ->> 'name');
    end if;
    if private.truthy(g -> 'required') and cardinality(idx) = 0 then
      raise exception '%', 'لازم تختار ' || coalesce(g ->> 'name', '');
    end if;
    foreach i in array idx loop
      c := g -> 'choices' -> i;
      base := base + coalesce(private.jnum(c -> 'price'), 0);
      f := private.jnum(c -> 'factor');
      if f is not null and f <> 0 then factor := factor * f; end if;
      picked := picked || jsonb_build_object('group', g ->> 'name', 'choice', c ->> 'name');
    end loop;
  end loop;
  return jsonb_build_object('unit', round(base * factor, 2), 'picked', picked);
end $$;

-- engine.js couponDiscount()
create or replace function private.coupon_discount(c public.coupons, subtotal numeric) returns jsonb
language plpgsql stable set search_path = '' as $$
declare d numeric;
begin
  if c.code is null or not c.active then return jsonb_build_object('ok', false, 'msg', 'الكود ده مش شغال'); end if;
  if c.expires_at is not null and c.expires_at < now() then return jsonb_build_object('ok', false, 'msg', 'الكود ده خلص'); end if;
  if c.max_uses > 0 and c.used >= c.max_uses then return jsonb_build_object('ok', false, 'msg', 'الكود ده اتستخدم للآخر'); end if;
  if subtotal < coalesce(c.min_order, 0) then return jsonb_build_object('ok', false, 'msg', 'الكود ده لطلبات من ' || private.money(c.min_order)); end if;
  d := case when c.type = 'percent' then round(subtotal * c.value / 100, 2) else c.value end;
  return jsonb_build_object('ok', true, 'discount', round(least(d, subtotal), 2),
    'msg', case when c.type = 'percent' then 'خصم ' || private.num_txt(c.value) || '%' else 'خصم ' || private.money(c.value) end);
end $$;

