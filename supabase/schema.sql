  insert into public.auth_events(kind, key, ip) values ('register', p, ip);
  return jsonb_build_object('token', private.new_session(c.id), 'profile', private.profile(c));
end $$;

/* Failed logins must be recorded even though the call "fails", and a raised
   exception would roll that record back. So login reports its errors as
   {"_err": "..."}; js/api.js turns that into a normal thrown error. */
create or replace function public.login(phone text default null, password text default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
#variable_conflict use_variable
declare p text := private.phone_norm(phone); k text; c public.customers; ip text := private.client_ip(); ok boolean;
begin
  k := coalesce(p, left(coalesce(phone, ''), 20));
  delete from public.auth_events e where e.at < now() - interval '2 days';
  if (select count(*) from public.auth_events e where e.kind = 'login_fail' and e.key = k and e.at > now() - interval '15 minutes') >= 5
     or (ip is not null and (select count(*) from public.auth_events e where e.kind = 'login_fail' and e.ip = ip and e.at > now() - interval '15 minutes') >= 20) then
    return jsonb_build_object('_err', 'محاولات غلط كتير — استنى ربع ساعة وجرّب تاني');
  end if;
  select * into c from public.customers x where x.phone = p;
  if c.id is null then
    perform extensions.crypt(coalesce(password, ''), extensions.gen_salt('bf', 10));   -- same timing as a real check
    ok := false;
  else
    ok := c.pass_hash = extensions.crypt(coalesce(password, ''), c.pass_hash);
  end if;
  if not ok then
    insert into public.auth_events(kind, key, ip) values ('login_fail', k, ip);
    return jsonb_build_object('_err', 'الرقم أو الباسورد غلط');
  end if;
  delete from public.auth_events e where e.kind = 'login_fail' and e.key = k;
  return jsonb_build_object('token', private.new_session(c.id), 'profile', private.profile(c));
end $$;

