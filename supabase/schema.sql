create or replace function public.validate_coupon(code text default null, subtotal numeric default 0) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare c public.coupons;
begin
  select * into c from public.coupons k where k.code = upper(btrim(coalesce(validate_coupon.code, '')));
