   It is idempotent: running it again keeps your data and only refreshes
   functions, grants and policies.

   Spec: the `handlers` object in js/engine.js (demo backend). Every RPC
   here returns the same shapes and the same Arabic messages.

   Security model
   - Tables live in `public` with RLS ON and NO policies, and every grant to
     anon/authenticated revoked → the API roles cannot read or write any
     table directly.
   - All access goes through SECURITY DEFINER functions with
     search_path = '' (everything schema-qualified).
   - admin_* functions call private.require_admin() first (Supabase Auth
     user listed in public.admins); they are also not executable by anon.
   - Customer passwords: bcrypt (pgcrypto). Session tokens: 256-bit random,
     stored as SHA-256, expire after 60 days. Login failures throttled.
   - Prices, discounts, totals, points and the delivery zone are computed
     here only; client-supplied prices are ignored.
   - place_order: size limits + per-phone and per-IP rate limits.
   ===================================================================== */

