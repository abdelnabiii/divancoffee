create or replace function private.require_admin() returns void
language plpgsql stable security definer set search_path = '' as $$
begin
  if auth.uid() is null or not exists (select 1 from public.admins a where a.user_id = auth.uid()) then
    raise exception using message = 'مش مسموح، ادخل تاني بحساب الأدمن', errcode = '42501';
  end if;
end $$;

-- Validates/normalises a product's option groups (admin input)
create or replace function private.clean_options(v jsonb) returns jsonb
language plpgsql immutable set search_path = '' as $$
declare g jsonb; c jsonb; out jsonb := '[]'::jsonb; ch jsonb; nc jsonb; pr numeric; fa numeric; gid text;
begin
  if v is null or jsonb_typeof(v) <> 'array' then return '[]'::jsonb; end if;
  if jsonb_array_length(v) > 20 then raise exception 'اختيارات كتير أوي في الصنف ده'; end if;
  for g in select value from jsonb_array_elements(v) loop
    if jsonb_typeof(g) <> 'object' or jsonb_typeof(g -> 'choices') <> 'array' then raise exception 'الاختيارات فيها بيانات غلط'; end if;
    if jsonb_array_length(g -> 'choices') > 40 then raise exception 'اختيارات كتير أوي في الصنف ده'; end if;
    gid := left(coalesce(nullif(btrim(g ->> 'id'), ''), 'g' || encode(extensions.gen_random_bytes(3), 'hex')), 40);
    ch := '[]'::jsonb;
    for c in select value from jsonb_array_elements(g -> 'choices') loop
      nc := jsonb_build_object('name', left(coalesce(c ->> 'name', ''), 60));
      pr := private.jnum(c -> 'price'); fa := private.jnum(c -> 'factor');
      if (c ? 'price' and c -> 'price' <> 'null'::jsonb and pr is null) or pr < 0 or pr > 100000
         or (c ? 'factor' and c -> 'factor' <> 'null'::jsonb and fa is null) or fa < 0 or fa > 100 then
        raise exception 'الاختيارات فيها رقم مش منطقي';
      end if;
      if pr is not null and pr <> 0 then nc := nc || jsonb_build_object('price', pr); end if;
      if fa is not null and fa <> 0 then nc := nc || jsonb_build_object('factor', fa); end if;
      ch := ch || nc;
    end loop;
    out := out || jsonb_build_object('id', gid, 'name', left(coalesce(g ->> 'name', ''), 60),
      'type', case when g ->> 'type' = 'multi' then 'multi' else 'single' end,
      'required', private.truthy(g -> 'required'), 'choices', ch);
  end loop;
  return out;
end $$;

