create or replace function private.client_ip() returns text
language plpgsql stable set search_path = '' as $$
declare h jsonb; ip text;
begin
  begin h := nullif(current_setting('request.headers', true), '')::jsonb; exception when others then h := null; end;
  if h is null then return null; end if;
  ip := coalesce(h ->> 'cf-connecting-ip', h ->> 'x-real-ip', split_part(h ->> 'x-forwarded-for', ',', 1));
  return left(nullif(btrim(ip), ''), 64);
end $$;

create or replace function private.cust_by_token(p_token text) returns public.customers
language sql stable security definer set search_path = '' as $$
  select c.* from public.customer_sessions s join public.customers c on c.id = s.customer_id
  where p_token is not null and length(p_token) = 64
    and s.token_hash = encode(extensions.digest(convert_to(p_token, 'UTF8'), 'sha256'), 'hex')
    and s.expires_at > now() $$;

create or replace function private.new_session(p_customer text) returns text
language plpgsql security definer set search_path = '' as $$
declare t text := encode(extensions.gen_random_bytes(32), 'hex');
begin
  delete from public.customer_sessions s where s.customer_id = p_customer and s.expires_at < now();
  insert into public.customer_sessions(token_hash, customer_id, expires_at)
  values (encode(extensions.digest(convert_to(t, 'UTF8'), 'sha256'), 'hex'), p_customer, now() + interval '60 days');
  return t;
end $$;

