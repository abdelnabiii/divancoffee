create or replace function public.change_password(token text default null, old_password text default null, new_password text default null) returns boolean
language plpgsql security definer set search_path = '' as $$
#variable_conflict use_variable
declare c public.customers := private.cust_by_token(token);
begin
  if c.id is null then raise exception 'سجّل دخول الأول'; end if;
  if c.pass_hash <> extensions.crypt(coalesce(old_password, ''), c.pass_hash) then raise exception 'الباسورد القديم غلط'; end if;
  if char_length(coalesce(new_password, '')) < 6 then raise exception 'الباسورد الجديد لازم 6 حروف أو أرقام على الأقل'; end if;
  if octet_length(new_password) > 72 then raise exception 'الباسورد طويل أوي'; end if;
  update public.customers x set pass_hash = extensions.crypt(new_password, extensions.gen_salt('bf', 10)) where x.id = c.id;
  -- sign out every other device
  delete from public.customer_sessions s where s.customer_id = c.id
    and s.token_hash <> encode(extensions.digest(convert_to(token, 'UTF8'), 'sha256'), 'hex');
  return true;
end $$;

