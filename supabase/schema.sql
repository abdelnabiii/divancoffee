create or replace function public.register(phone text default null, name text default null, password text default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
#variable_conflict use_variable
declare p text := private.phone_norm(phone); n text := btrim(coalesce(name, '')); c public.customers; ip text := private.client_ip();
begin
  if p is null then raise exception 'رقم الموبايل مش صح'; end if;
  if char_length(n) < 2 then raise exception 'اكتب اسمك'; end if;
  if char_length(coalesce(password, '')) < 6 then raise exception 'الباسورد لازم 6 حروف أو أرقام على الأقل'; end if;
  if octet_length(password) > 72 then raise exception 'الباسورد طويل أوي'; end if;
  if exists (select 1 from public.customers x where x.phone = p) then raise exception 'الرقم ده متسجّل قبل كده، ادخل بيه'; end if;
  if ip is not null and (select count(*) from public.auth_events e where e.kind = 'register' and e.ip = ip and e.at > now() - interval '1 hour') >= 10 then
    raise exception 'محاولات كتير — استنى شوية وجرّب تاني';
  end if;
  insert into public.customers(phone, name, pass_hash) values (p, left(n, 60), extensions.crypt(password, extensions.gen_salt('bf', 10)))
