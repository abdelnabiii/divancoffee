end $$;

create or replace function public.place_order(payload jsonb default null, token text default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
#variable_conflict use_variable
declare
  o jsonb := coalesce(payload, '{}'::jsonb); s jsonb := private.settings();
  v_type text; v_name text; v_phone text; v_table int; v_addr text := ''; v_lat float8; v_lng float8; v_dist numeric;
  d float8; it jsonb; p public.products; q int; lu jsonb; v_items jsonb := '[]'::jsonb; v_sub numeric := 0; v_unit numeric; v_line numeric;
  v_disc numeric := 0; v_coupon text; cref public.coupons; r jsonb; cust public.customers; want int; pv numeric;
  v_used int := 0; pval numeric; fee numeric; net numeric; v_total numeric; earned int := 0; ord public.orders;
  ip text := private.client_ip(); radius numeric;
begin
  if jsonb_typeof(o) <> 'object' then raise exception 'السلة فاضية'; end if;
  if octet_length(o::text) > 32000 then raise exception 'الطلب كبير أوي، كلمنا على التليفون'; end if;
  if not private.truthy(s -> 'accepting') then raise exception 'الكافيه مش بيستقبل طلبات أونلاين دلوقتي'; end if;
  v_type := o ->> 'type';
  if v_type is null or v_type not in ('delivery','pickup','table') or not private.truthy(s -> (v_type || '_enabled')) then
    raise exception 'نوع الطلب ده مش متاح';
  end if;
  v_name := btrim(coalesce(o ->> 'name', ''));
  if char_length(v_name) < 2 then raise exception 'اكتب اسمك'; end if;
  v_name := left(v_name, 60);
  v_phone := private.phone_norm(o ->> 'phone');
  if v_phone is null then raise exception 'رقم الموبايل مش صح'; end if;

  -- anti-abuse: per phone and per client IP
  if (select count(*) from public.orders x where x.phone = v_phone and x.created_at > now() - interval '10 minutes') >= 5
     or (select count(*) from public.orders x where x.phone = v_phone and x.created_at > now() - interval '1 day') >= 30
     or (ip is not null and (select count(*) from public.orders x where x.client_ip = ip and x.created_at > now() - interval '10 minutes') >= 40) then
    raise exception 'طلبات كتير في وقت قصير — استنى شوية أو كلمنا على التليفون';
  end if;

  if v_type = 'table' then
    v_table := private.jint(o -> 'table_no');
    if v_table is null or v_table < 1 or v_table > coalesce(private.jnum(s -> 'tables_count'), 0) then raise exception 'رقم الترابيزة مش صح'; end if;
  end if;
  if v_type = 'delivery' then
    v_addr := btrim(coalesce(o ->> 'address', ''));
    if char_length(v_addr) < 8 then raise exception 'اكتب العنوان بالتفصيل'; end if;
    v_addr := left(v_addr, 300);
    if not private.valid_ll(o -> 'lat', o -> 'lng') then raise exception 'حدد موقعك عشان نتأكد إنك في منطقة التوصيل'; end if;
    v_lat := private.jnum(o -> 'lat'); v_lng := private.jnum(o -> 'lng');
    radius := private.jnum(s -> 'delivery_radius_km');
    d := private.dist_km(private.jnum(s -> 'cafe_lat')::float8, private.jnum(s -> 'cafe_lng')::float8, v_lat, v_lng);
    if radius is null or d > radius then
      raise exception '%', 'الزون ده مش متاح للتوصيل — بنوصّل لحد ' || coalesce(private.num_txt(radius), '0') || ' كم من الكافيه';
    end if;
    v_dist := round(d::numeric, 1);
  end if;

  if jsonb_typeof(o -> 'items') <> 'array' or jsonb_array_length(o -> 'items') = 0 then raise exception 'السلة فاضية'; end if;
  if jsonb_array_length(o -> 'items') > 40 then raise exception 'الطلب كبير أوي، كلمنا على التليفون'; end if;
  for it in select value from jsonb_array_elements(o -> 'items') loop
    select * into p from public.products x where x.id = (it ->> 'pid') and x.active;
    if not found then raise exception 'في صنف في السلة مبقاش متاح، شيله وكمّل'; end if;
    if not p.available then raise exception '%', format('"%s" خلص النهارده', p.name); end if;
    q := private.jint(it -> 'qty');
    if q is null or q < 1 or q > 50 then raise exception 'الكمية مش صح'; end if;
    lu := private.line_unit(p.options, p.price, it -> 'sel');      -- price comes from the DB, never the client
    v_unit := (lu ->> 'unit')::numeric;
    v_line := round(v_unit * q, 2);
    v_sub := round(v_sub + v_line, 2);
    v_items := v_items || jsonb_build_object('pid', p.id, 'name', p.name, 'qty', q, 'unit', v_unit, 'line', v_line,
      'options', lu -> 'picked', 'note', left(coalesce(it ->> 'note', ''), 120));
  end loop;
  if v_sub < coalesce(private.jnum(s -> 'min_order'), 0) then
    raise exception '%', 'أقل طلب ' || private.money(private.jnum(s -> 'min_order'));
  end if;

  if coalesce(o ->> 'coupon', '') <> '' then
    select * into cref from public.coupons k where k.code = upper(btrim(o ->> 'coupon')) for update;
    if not found then raise exception 'الكود ده مش موجود'; end if;
    r := private.coupon_discount(cref, v_sub);
    if not (r ->> 'ok')::boolean then raise exception '%', r ->> 'msg'; end if;
    v_disc := (r ->> 'discount')::numeric; v_coupon := cref.code;
  end if;

  cust := private.cust_by_token(token);
  if cust.id is not null then select * into cust from public.customers c where c.id = cust.id for update; end if;
  want := greatest(0, coalesce(private.jint(o -> 'points'), 0));
  pv := coalesce(nullif(private.jnum(s -> 'point_value'), 0), 1);
  if want > 0 then
    if cust.id is null then raise exception 'سجّل دخول عشان تستخدم حبّاتك'; end if;
    v_used := greatest(0, least(want, cust.points, floor((v_sub - v_disc) / pv)::int));
  end if;
  pval := round(v_used * pv, 2);
  fee := case when v_type = 'delivery' then coalesce(private.jnum(s -> 'delivery_fee'), 0) else 0 end;
  net := round(v_sub - v_disc - pval, 2);
  v_total := round(net + fee, 2);
  if cust.id is not null then
    earned := least(coalesce(private.jnum(s -> 'points_cap'), 0), floor(round(net * coalesce(private.jnum(s -> 'cashback_rate'), 0), 2)))::int;
  end if;
  if cust.id is not null and v_used > 0 then update public.customers c set points = c.points - v_used where c.id = cust.id; end if;
  if cref.code is not null then update public.coupons k set used = k.used + 1 where k.code = cref.code; end if;

  insert into public.orders(track, customer_id, name, phone, type, table_no, address, lat, lng, distance_km, notes, items,
    subtotal, discount, coupon, points_used, delivery_fee, total, points_earned, client_ip)
  values (encode(extensions.gen_random_bytes(12), 'hex'), cust.id, v_name, v_phone, v_type, v_table, v_addr, v_lat, v_lng, v_dist,
    left(coalesce(o ->> 'notes', ''), 300), v_items, v_sub, v_disc, v_coupon, v_used, fee, v_total, earned, ip)
  returning * into ord;
  return private.public_order(ord);
end $$;

