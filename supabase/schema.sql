create or replace function public.admin_set_status(id bigint default null, status text default null) returns boolean
language plpgsql security definer set search_path = '' as $$
declare o public.orders; c public.customers; st text := admin_set_status.status; has_c boolean;
begin
  perform private.require_admin();
  select * into o from public.orders x where x.id = admin_set_status.id for update;
  if not found then raise exception 'الطلب مش موجود'; end if;
  if st is null or st not in ('new','preparing','ready','out','done','cancelled') then raise exception 'حالة غلط'; end if;
  if o.customer_id is not null then select * into c from public.customers x where x.id = o.customer_id for update; end if;
  has_c := c.id is not null;
  if st = 'done' and not o.awarded and has_c then c.points := c.points + o.points_earned; o.awarded := true; end if;
  if st <> 'done' and o.awarded and has_c then c.points := greatest(0, c.points - o.points_earned); o.awarded := false; end if;
  if st = 'cancelled' and not o.refunded and has_c and o.points_used > 0 then c.points := c.points + o.points_used; o.refunded := true; end if;
  if st <> 'cancelled' and o.refunded and has_c then c.points := greatest(0, c.points - o.points_used); o.refunded := false; end if;
  if has_c then update public.customers x set points = c.points where x.id = c.id; end if;
  update public.orders x set status = st, awarded = o.awarded, refunded = o.refunded where x.id = o.id;
  return true;
end $$;

